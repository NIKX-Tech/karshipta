TEST(Gt06Parser, RealDeviceCaptureCorpusNeverComesBackInvalid) {
    int total_frames = 0;
    int unsupported = 0;
    int checksum_mismatches = 0;
    for (const auto& hex : kRealGt06Captures) {
        std::vector<uint8_t> bytes = hex_to_bytes(hex);
        std::span<const uint8_t> remaining(bytes);
        while (!remaining.empty()) {
            const auto result = Gt06Parser::parse_frame(remaining);
            ASSERT_NE(result.result, Gt06Parser::FrameResult::kInvalid)
                << "capture rejected as invalid: " << hex;
            if (result.result == Gt06Parser::FrameResult::kIncomplete) break;
            total_frames++;
            if (result.packet.type == Gt06Parser::PacketType::kUnsupported) unsupported++;
            if (result.checksum_mismatch) checksum_mismatches++;
            remaining = remaining.subspan(result.consumed_bytes);
        }
    }
    // Pins down this session's own findings as a permanent regression
    // check, not just "nothing crashed" - if a future Traccar test-suite
    // update changes these counts, that is real new signal worth looking
    // at again, not noise to silently tolerate. 189, not 185: a handful of
    // captures need the stop-marker fallback scan (see parse_frame) to find
    // their real per-frame boundaries at all, which changes how many
    // complete frames some concatenated-capture lines actually yield versus
    // an earlier, cruder count taken before that fallback existed - this
    // includes one genuine, complete, correctly-terminated 6-byte frame
    // that an earlier version of this fix's own minimum-length gate (fixed
    // at 10/11 bytes) still rejected as permanently incomplete, caught by
    // an independent review (RealSixByteCaptureWithDegenerateLengthIsNot
    // StuckIncomplete above exercises it directly). 15, not 24: nine of
    // what first looked like genuine device checksum mismatches were
    // actually this parser computing the checksum over the wrong byte
    // range because the frame boundary itself was still wrong at the time -
    // fixing the boundary fixed those for real, leaving 15 genuine ones.
    EXPECT_EQ(total_frames, 189);
    EXPECT_EQ(checksum_mismatches, 15);
    EXPECT_GT(unsupported, 0);  // this parser only decodes login/location/heartbeat content
}

