// github#283: confirmed against 185 real device captures (Traccar's own
// test suite) that a checksum mismatch on an otherwise well-framed packet
// is normal, tolerated real-device firmware behavior, not corruption -
// Traccar's own reference decoder never validates the incoming checksum at
// all. Still decodes normally; the mismatch is surfaced via
// checksum_mismatch for the caller to log, not treated as fatal.
TEST(Gt06Parser, CorruptedChecksumStillDecodesButFlagsTheMismatch) {
    // Real login frame (see LoginPacketDecodesImei below) with the last
    // checksum byte flipped.
    std::vector<uint8_t> data = {0x78, 0x78, 0x0F, 0x01, 0x08, 0x61, 0x84, 0x50, 0x41,
                                  0x23, 0x45, 0x67, 0x01, 0x02, 0x00, 0x01, 0x58, 0x5C,
                                  0x0D, 0x0A};
    data[17] ^= 0xFF;
    const auto result = Gt06Parser::parse_frame(data);
    ASSERT_EQ(result.result, Gt06Parser::FrameResult::kOk);
    EXPECT_TRUE(result.checksum_mismatch);
    EXPECT_EQ(result.packet.type, Gt06Parser::PacketType::kLogin);
    ASSERT_TRUE(result.packet.imei.has_value());
    EXPECT_EQ(*result.packet.imei, "861845041234567");
}

// A real capture from Traccar's own test suite (Gt06ProtocolDecoderTest.java)
// that genuinely fails CRC-16/X-25 over its own bytes - independently
// re-verified with a from-scratch Python implementation of the same
// algorithm before trusting this as a real device quirk rather than a bug
// in this parser's own crc16_x25. Traccar's test expects this exact capture
// to decode successfully (asserting a low-battery alarm attribute); type
// 0x19 isn't one this parser decodes content for, so it lands as
