// A real capture (6 bytes total) whose declared length_value (1) is too
// degenerate to describe type+serial+checksum at all, found by an
// independent review of this fix: an earlier version of parse_frame gated
// on a fixed 10/11-byte minimum before even looking at the length field or
// attempting the stop-marker fallback scan, so this genuine, complete,
// correctly-terminated frame was stuck as kIncomplete forever - silently
// lost if the connection ended before 4 more arbitrary bytes happened to
// arrive. Traccar's own frame decoder has no such premature minimum; this
// doesn't either now.
TEST(Gt06Parser, RealSixByteCaptureWithDegenerateLengthIsNotStuckIncomplete) {
    const std::vector<uint8_t> data = {0x78, 0x78, 0x01, 0x08, 0x0d, 0x0a};
    const auto result = Gt06Parser::parse_frame(data);
    ASSERT_EQ(result.result, Gt06Parser::FrameResult::kOk);
    EXPECT_EQ(result.consumed_bytes, data.size());
    EXPECT_EQ(result.packet.type, Gt06Parser::PacketType::kUnsupported);
}

// github#283: the declared length field is sometimes simply wrong (see
// RealCaptureWithOffByOneLengthStillRecoversViaStopMarkerScan below), so a
// stop marker missing from its *declared* position no longer means
// kInvalid on its own - parse_frame falls back to scanning for the next
// literal 0x0D 0x0A instead, matching Traccar's own Gt06FrameDecoder. This
// corruption removes the only 0x0D byte in the buffer entirely, so no
// fallback scan can find one anywhere either: kIncomplete (keep waiting
// for more bytes, in case a real terminator is still coming), not
// kInvalid - exactly what Traccar's own frame decoder does in this
// situation too (it returns null, not an error).
TEST(Gt06Parser, NoStopMarkerAnywhereInBufferIsIncompleteNotInvalid) {
    std::vector<uint8_t> data = {0x78, 0x78, 0x0F, 0x01, 0x08, 0x61, 0x84, 0x50, 0x41,
                                  0x23, 0x45, 0x67, 0x01, 0x02, 0x00, 0x01, 0x58, 0x5C,
                                  0x0D, 0x0A};
    data[18] = 0xFF;
    const auto result = Gt06Parser::parse_frame(data);
    EXPECT_EQ(result.result, Gt06Parser::FrameResult::kIncomplete);
}

